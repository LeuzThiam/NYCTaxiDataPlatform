-- 1. Rôle et utilisateur de service (créés par USERADMIN)
USE ROLE USERADMIN;

CREATE ROLE IF NOT EXISTS NYC_TAXI_PIPELINE;

CREATE USER IF NOT EXISTS SVC_NYC_TAXI
    TYPE = SERVICE
    DEFAULT_ROLE = 'NYC_TAXI_PIPELINE'
    DEFAULT_WAREHOUSE = 'WH_NYC_TAXI';

GRANT ROLE NYC_TAXI_PIPELINE TO USER SVC_NYC_TAXI;
GRANT ROLE NYC_TAXI_PIPELINE TO ROLE SYSADMIN;

-- 2. Droits sur les objets du projet (accordés par SYSADMIN, leur propriétaire)
USE ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE WH_NYC_TAXI TO ROLE NYC_TAXI_PIPELINE;
GRANT USAGE ON DATABASE NYC_TAXI TO ROLE NYC_TAXI_PIPELINE;
GRANT USAGE ON SCHEMA NYC_TAXI.BRONZE TO ROLE NYC_TAXI_PIPELINE;

GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA NYC_TAXI.BRONZE TO ROLE NYC_TAXI_PIPELINE;
GRANT SELECT, INSERT ON FUTURE TABLES IN SCHEMA NYC_TAXI.BRONZE TO ROLE NYC_TAXI_PIPELINE;

GRANT READ, WRITE ON STAGE NYC_TAXI.BRONZE.STG_RAW TO ROLE NYC_TAXI_PIPELINE;