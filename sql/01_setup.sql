USE ROLE SYSADMIN;

-- Entrepôt de calcul : plus petite taille, suspension automatique après 60 s
CREATE WAREHOUSE IF NOT EXISTS WH_NYC_TAXI
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- Base de données du projet
CREATE DATABASE IF NOT EXISTS NYC_TAXI;

-- Les trois couches de l'architecture
CREATE SCHEMA IF NOT EXISTS NYC_TAXI.BRONZE;
CREATE SCHEMA IF NOT EXISTS NYC_TAXI.SILVER;
CREATE SCHEMA IF NOT EXISTS NYC_TAXI.GOLD;